/**
 * Weekly Report Service  (Ticket 3.2)
 *
 * For each account with sendWeeklyReport = true:
 *   1. Fetches account contacts + email configuration
 *   2. Generates PDF schedule + Excel hours files
 *   3. Skips delivery if no files were generated or no valid email present
 *   4. Emails via Microsoft Graph with both files as attachments
 *   5. Logs the delivery result to report_delivery_logs
 *
 * Email format:
 *   Subject: Weekly Driver Schedule & Hours – {Account Name} – Week of {WeekStartDate}
 *   Body:    Hi {Contact Name}, Attached are your weekly reports…
 *   Attachments: Schedule_{Account}_{Week}.pdf, Hours_{Account}_{Week}.xlsx
 */

