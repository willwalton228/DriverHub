const DEFAULT_TRAVEL_RADIUS = 50;

function haversineDistance(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 3958.8;
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLng = (lng2 - lng1) * Math.PI / 180;
  const a = Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) *
    Math.sin(dLng / 2) * Math.sin(dLng / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

export function getCoordinatesFromZip(zipCode: string): { lat: number; lng: number } | null {
  if (!zipCode || zipCode.length < 3) return null;
  const prefix = zipCode.substring(0, 3);
  return ZIP_PREFIX_COORDINATES[prefix] || null;
}

export function getMarketCoordinates(market: string): { lat: number; lng: number } | null {
  if (!market) return null;
  const directMatch = MARKET_COORDINATES[market];
  if (directMatch) return directMatch;
  const normalizedMarket = market.toLowerCase().trim();
  for (const [key, coords] of Object.entries(MARKET_COORDINATES)) {
    if (key.toLowerCase() === normalizedMarket) return coords;
  }
  for (const [key, coords] of Object.entries(MARKET_COORDINATES)) {
    if (normalizedMarket.includes(key.toLowerCase()) || key.toLowerCase().includes(normalizedMarket)) {
      return coords;
    }
  }
  return null;
}

export function calculateDistance(
  candidateZip: string | null | undefined,
  candidateLat: string | number | null | undefined,
  candidateLng: string | number | null | undefined,
  market: string | null | undefined
): { distanceMiles: number; candidateCoords: { lat: number; lng: number }; marketCoords: { lat: number; lng: number } } | null {
  if (!market) return null;

  const marketCoords = getMarketCoordinates(market);
  if (!marketCoords) return null;

  let candidateCoords: { lat: number; lng: number } | null = null;

  if (candidateLat && candidateLng) {
    candidateCoords = {
      lat: typeof candidateLat === 'string' ? parseFloat(candidateLat) : candidateLat,
      lng: typeof candidateLng === 'string' ? parseFloat(candidateLng) : candidateLng,
    };
  }

  if (!candidateCoords && candidateZip) {
    candidateCoords = getCoordinatesFromZip(candidateZip);
  }

  if (!candidateCoords) return null;

  const distanceMiles = haversineDistance(
    candidateCoords.lat, candidateCoords.lng,
    marketCoords.lat, marketCoords.lng
  );

  return {
    distanceMiles: Math.round(distanceMiles * 10) / 10,
    candidateCoords,
    marketCoords,
  };
}

export function determineGeoEligibility(
  distanceMiles: number | null,
  maxTravelRadius: number | null | undefined
): boolean | null {
  if (distanceMiles === null) return null;
  const radius = maxTravelRadius || DEFAULT_TRAVEL_RADIUS;
  return distanceMiles <= radius;
}

export async function computeAndUpdateGeoEligibility(applicationId: string): Promise<{
  distanceMiles: number | null;
  geoEligible: boolean | null;
} | null> {
  const application = await db.query.recruitingApplications.findFirst({
    where: (apps, { eq }) => eq(apps.id, applicationId),
  });
  if (!application) return null;

  const candidate = await db.query.recruitingCandidates.findFirst({
    where: (cands, { eq }) => eq(cands.id, application.candidateId),
  });
  if (!candidate) return null;

  const requisition = await db.query.recruitingRequisitions.findFirst({
    where: (reqs, { eq }) => eq(reqs.id, application.requisitionId),
  });
  if (!requisition) return null;

  const result = calculateDistance(
    candidate.zipCode,
    candidate.latitude,
    candidate.longitude,
    requisition.market
  );

  const distanceMiles = result ? result.distanceMiles : null;
  const geoEligible = determineGeoEligibility(distanceMiles, candidate.maxTravelRadius);

  const updateData: Record<string, any> = {
    geoCalculatedAt: new Date(),
    updatedAt: new Date(),
  };

  if (distanceMiles !== null) {
    updateData.distanceMiles = String(distanceMiles);
  }
  if (geoEligible !== null) {
    updateData.geoEligible = geoEligible;
  } else {
    updateData.geoEligible = null;
  }

  await db.update(recruitingApplications)
    .set(updateData)
    .where(eq(recruitingApplications.id, applicationId));

  if (result && !candidate.latitude) {
    await db.update(recruitingCandidates)
      .set({
        latitude: String(result.candidateCoords.lat),
        longitude: String(result.candidateCoords.lng),
        updatedAt: new Date(),
      })
      .where(eq(recruitingCandidates.id, candidate.id));
  }

  return { distanceMiles, geoEligible };
}

export async function refreshGeoForCandidate(candidateId: string): Promise<void> {
  const applications = await db.query.recruitingApplications.findMany({
    where: (apps, { eq, and }) => and(
      eq(apps.candidateId, candidateId),
      eq(apps.isArchived, false)
    ),
  });

  for (const app of applications) {
    await computeAndUpdateGeoEligibility(app.id);
  }
}
